"""Write android/ and web/ from masters/ as listed in manifest.json.

    python3 tools/export.py          (run from the repository root)

Needs Pillow with WebP support and rsvg-convert (librsvg). Outputs are
committed, so the app and the website use them without running this.

- art: WebP at 640 px (Android drawable-nodpi, the size the app used before)
  and at 640 px for the web.
- launcher: PNG per density on the 108 dp adaptive-icon grid.
- notification: the visor alone, cropped to its square, white, 24 dp per density.
- mark: an Android VectorDrawable converted from the SVG, and for the web the
  SVG itself plus favicon and app icon PNGs.
"""
import json
import os
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
ART_PX = 640
# The visor spans x 25..83 on the 108 grid; the notification icon crops to this square around it.
NOTIFICATION_VIEWBOX = "21 21 66 66"


def path(*parts):
    p = os.path.join(ROOT, *parts)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    return p


def render_svg(svg, px, out, viewbox=None):
    src = svg
    if viewbox:
        text = open(svg).read()
        text = re.sub(r'viewBox="[^"]*"', f'viewBox="{viewbox}"', text, count=1)
        tmp = tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False)
        tmp.write(text); tmp.close(); src = tmp.name
    subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), src, "-o", out], check=True)
    if viewbox:
        os.unlink(src)


def load(master, px):
    m = os.path.join(ROOT, master)
    if m.endswith(".svg"):
        with tempfile.NamedTemporaryFile(suffix=".png") as t:
            render_svg(m, px, t.name)
            return Image.open(t.name).convert("RGBA").copy()
    return Image.open(m).convert("RGBA").resize((px, px), Image.LANCZOS)


def webp(im, out):
    im.save(out, "WEBP", quality=90, method=6)


def android_res(target):
    return {"designsystem": ("android", "designsystem", "res"),
            "app": ("android", "app", "res"),
            "app-live": ("android", "app-live", "res")}[target]


def vector_drawable(svg, out, comment):
    """Convert the mark's SVG (paths and circles with fill or stroke) to a VectorDrawable."""
    ns = {"s": "http://www.w3.org/2000/svg"}
    root = ET.parse(svg).getroot()
    vx, vy, vw, vh = root.get("viewBox").split()
    lines = []
    for el in root:
        tag = el.tag.split("}")[1]
        if tag == "circle":
            cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
            d = f"M{cx - r:g},{cy}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0"
        elif tag == "path":
            d = el.get("d")
        else:
            continue
        attrs = []
        fill = el.get("fill")
        if fill and fill != "none":
            attrs.append(f'android:fillColor="{expand(fill)}"')
        if el.get("stroke"):
            attrs.append(f'android:strokeColor="{expand(el.get("stroke"))}"')
            attrs.append(f'android:strokeWidth="{el.get("stroke-width", "1")}"')
        attrs.append(f'android:pathData="{d}"')
        lines.append(f'    <path {" ".join(attrs)} />')
    with open(out, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write(f"<!-- {comment} Generated by brand/tools/export.py from {os.path.relpath(svg, ROOT)}. -->\n")
        f.write('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n')
        f.write(f'    android:width="{vw}dp" android:height="{vh}dp"\n')
        f.write(f'    android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n')
        f.write("\n".join(lines) + "\n</vector>\n")


def expand(c):
    c = c.upper()
    if re.fullmatch(r"#[0-9A-F]{3}", c):
        c = "#" + "".join(ch * 2 for ch in c[1:])
    return c


def main():
    for d in ("android", "web"):
        shutil.rmtree(os.path.join(ROOT, d), ignore_errors=True)
    manifest = json.load(open(os.path.join(ROOT, "manifest.json")))
    for a in manifest["assets"]:
        name, master, kind, target = a["name"], a["master"], a["kind"], a["android"]
        if kind == "art":
            im = load(master, ART_PX)
            if target:
                webp(im, path(*android_res(target), "drawable-nodpi", f"{name}.webp"))
            if a["web"]:
                webp(im, path("web", f"{name}.webp"))
        elif kind == "launcher":
            for dens, k in DENSITIES.items():
                render_svg(os.path.join(ROOT, master), round(108 * k), path(*android_res(target), f"drawable-{dens}", f"{name}.png"))
        elif kind == "notification":
            for dens, k in DENSITIES.items():
                render_svg(os.path.join(ROOT, master), round(24 * k), path(*android_res(target), f"drawable-{dens}", f"{name}.png"), NOTIFICATION_VIEWBOX)
        elif kind == "mark":
            svg = os.path.join(ROOT, master)
            vector_drawable(svg, path(*android_res(target), "drawable", f"{name}.xml"),
                            "The ShopNexus mark: a shopping bag whose handle joins two nodes; the terracotta dot is the price tag.")
            if a["web"]:
                shutil.copy(svg, path("web", "brand_mark.svg"))
        elif kind == "app_icon":
            # The web's favicon and app icons are the launcher's face on its mint, as on Android.
            svg = os.path.join(ROOT, master)
            shutil.copy(svg, path("web", "favicon.svg"))
            for px, fname in ((32, "favicon-32.png"), (180, "apple-touch-icon.png"), (192, "icon-192.png"), (512, "icon-512.png")):
                render_svg(svg, px, path("web", fname))
    print("exported", len(manifest["assets"]), "assets")


if __name__ == "__main__":
    main()
